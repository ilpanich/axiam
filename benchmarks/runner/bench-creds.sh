#!/usr/bin/env bash
# bench-creds.sh — per-stack benchmark credentials. SOURCE this file; do not run it.
#
# No benchmark credential is a literal anywhere in this repository (the CodeQL
# "hard-coded credentials" rule, and the lesson of T23.10.1's authentik target).
# Every one is generated here, once per stack, and then travels like this:
#
#   1. `just target=<t> bench-up` calls bench_creds_load, which creates
#      .seed/<t>.stack.env (mode 600, gitignored) the first time and sources it
#      every time. The compose files take each credential from a REQUIRED
#      variable (`${VAR:?…}`), so a raw `docker compose up` fails closed instead
#      of starting a stack whose password is in the repository.
#   2. runner/seed.sh calls bench_creds_load too, provisions the fixture with
#      those values, and writes the ones the k6 scenarios and the SDK benches
#      need (the bench user's password, the bootstrap admin's, Keycloak's) into
#      .seed/<t>.seed.env, which run-benchmark.sh sources.
#   3. `just target=<t> bench-down` removes the stack file with the volumes it
#      belongs to: a surviving file would hand the next stack a password for data
#      that no longer exists.
#
# A value already present in the caller's environment ALWAYS wins and is what the
# stack file records (the FAPI conformance workflow exports BENCH_ADMIN_PASSWORD
# before bench-up, and that must keep working). The stack file is written as
# `[ -n "${VAR:-}" ] || VAR='value'` lines for the same reason: sourcing it never
# overrides an environment the operator set.
#
# Nothing here prints a credential. Under GitHub Actions every value is
# registered with the log scrubber (::add-mask::) as it is loaded.
#
# By hand (a k6 scenario outside the runner): `source .seed/<t>.seed.env` exports
# BENCH_PASSWORD, BENCH_CLIENT_SECRET, BENCH_ADMIN_PASSWORD and KC_ADMIN_PASSWORD;
# nothing else is needed. See benchmarks/README.md, "Credentials".

BENCH_CREDS_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

bench_creds_file() {  # TARGET -> path of the stack file
  printf '%s/%s.stack.env' "${BENCH_SEED_DIR:-$BENCH_CREDS_ROOT/.seed}" "$1"
}

# The variable names a target's stack needs, one per line. Kinds: `pw` is a
# password a human-facing policy may judge (upper, lower, digit, symbol, 40
# characters); `hex` is an infrastructure secret (hex only, so it is safe in a
# URL, a command line and a JDBC string); `hex16` is Zitadel's masterkey, which
# must be exactly 32 characters.
bench_creds_spec() {  # TARGET -> "NAME kind" lines
  case "$1" in
    axiam)
      printf '%s\n' \
        "AXIAM__DB__PASSWORD hex" \
        "RABBITMQ_DEFAULT_PASS hex" \
        "BENCH_ADMIN_PASSWORD pw" \
        "BENCH_PASSWORD pw" ;;
    keycloak)
      printf '%s\n' \
        "KC_ADMIN_PASSWORD pw" \
        "BENCH_KC_DB_PASSWORD hex" \
        "BENCH_PASSWORD pw" ;;
    zitadel)
      printf '%s\n' \
        "BENCH_ZITADEL_MASTERKEY hex16" \
        "BENCH_ZITADEL_DB_USER_PASSWORD hex" \
        "BENCH_ZITADEL_DB_ADMIN_PASSWORD hex" \
        "BENCH_PASSWORD pw" ;;
    authentik)
      # BENCH_PASSWORD is generated by the authentik seed itself (it has to set it
      # through authentik's API); everything else is here.
      printf '%s\n' \
        "BENCH_AUTHENTIK_SECRET_KEY hex64" \
        "BENCH_AUTHENTIK_PG_PASSWORD hex" \
        "BENCH_AUTHENTIK_ADMIN_PASSWORD pw" \
        "BENCH_AUTHENTIK_ADMIN_TOKEN hex64" ;;
    *) return 1 ;;
  esac
}

_bench_creds_gen() {  # KIND -> a fresh value on stdout
  case "$1" in
    pw)     printf 'Bn-%s-Aa1' "$(openssl rand -hex 16)" ;;
    hex)    openssl rand -hex 16 ;;
    hex16)  openssl rand -hex 16 ;;   # 32 hex characters: Zitadel's masterkey length
    hex64)  openssl rand -hex 32 ;;
    *)      return 1 ;;
  esac
}

# Create .seed/<target>.stack.env if it does not exist. Idempotent. A name the
# environment already carries is recorded with ITS value.
bench_creds_ensure() {  # TARGET
  local target="$1" file name kind val
  file="$(bench_creds_file "$target")"
  bench_creds_spec "$target" >/dev/null || { echo "[creds] unknown target '$target'" >&2; return 1; }
  [ -s "$file" ] && return 0
  command -v openssl >/dev/null || { echo "[creds] openssl is required to generate per-run credentials" >&2; return 1; }
  mkdir -p "$(dirname "$file")"
  echo "[creds] generating per-run $target credentials into ${file#"$BENCH_CREDS_ROOT"/} (mode 600; bench-down removes it)" >&2
  (
    umask 077
    {
      echo "# Generated by runner/bench-creds.sh for target=$target. Per-run credentials; never commit."
      while read -r name kind; do
        [ -n "$name" ] || continue
        val="${!name:-}"
        [ -n "$val" ] || val="$(_bench_creds_gen "$kind")"
        # Single-quoted, an embedded quote escaped, so no value is ever
        # re-expanded by the shell that sources the file.
        val="${val//\'/\'\\\'\'}"
        printf '[ -n "${%s:-}" ] || %s='\''%s'\''\nexport %s\n' "$name" "$name" "$val" "$name"
      done < <(bench_creds_spec "$target")
    } > "$file"
  )
}

# Ensure, source, and (under GitHub Actions) register every value as a secret.
bench_creds_load() {  # TARGET
  local target="$1" file name kind
  bench_creds_ensure "$target" || return 1
  file="$(bench_creds_file "$target")"
  # shellcheck disable=SC1090
  . "$file"
  if [ "${GITHUB_ACTIONS:-}" = "true" ]; then
    while read -r name kind; do
      [ -n "$name" ] && [ -n "${!name:-}" ] && printf '::add-mask::%s\n' "${!name}"
    done < <(bench_creds_spec "$target")
  fi
  return 0
}

# Remove a target's stack file (bench-down).
bench_creds_remove() {  # TARGET
  rm -f "$(bench_creds_file "$1")"
}
