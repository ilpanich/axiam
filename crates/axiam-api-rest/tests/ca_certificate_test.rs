#[actix_web::test]
async fn an_imported_ca_can_sign_a_leaf_certificate() {
    // The whole point of importing a key rather than only a certificate. This
    // also exercises the custody read path end to end: the CA record says
    // `database`, and the signing path asks the record.
    let (db, org_id, tenant_id) = setup_db().await;
    let user_id = create_admin_user(&db, tenant_id).await;
    let auth = test_auth_config();
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let app = test_app!(db, auth);
    let (key_pem, cert_pem) = external_ca("Signing Root");

    let (status, ca) = post_import(
        &app,
        org_id,
        &token,
        serde_json::json!({
            "public_cert_pem": cert_pem,
            "private_key_pem": key_pem,
        }),
    )
    .await;
    assert_eq!(status, 201, "{ca}");

    let req = test::TestRequest::post()
        .uri("/api/v1/certificates")
        .insert_header(("Authorization", format!("Bearer {token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .set_json(serde_json::json!({
            "issuer_ca_id": ca["id"],
            "subject": "CN=device-1",
            "cert_type": "Device",
            "key_algorithm": "Ed25519",
            "validity_days": 30,
        }))
        .to_request();
    let resp = test::call_service(&app, req).await;
    let leaf_status = resp.status().as_u16();
    let leaf: serde_json::Value = test::read_body_json(resp).await;
    assert_eq!(leaf_status, 201, "{leaf}");
    assert!(leaf["private_key_pem"].is_string(), "{leaf}");
}

