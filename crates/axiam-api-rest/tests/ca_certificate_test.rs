// ---------------------------------------------------------------------------
// Importing a CA the organization already has (BYOK)
// ---------------------------------------------------------------------------
//
// The case an organization with an offline root, an HSM, or an existing
// internal PKI needs: AXIAM in the chain rather than at the top of it. Without
// it the only usable CA is one AXIAM generated, which means every
// AXIAM-issued certificate chains to a root nothing else in the estate trusts.

/// A self-signed CA, the way an external PKI hands one over.
///
/// The validity window is rcgen's default, which is far in the future — these
/// tests are about the import path, and `parse_ca_certificate`'s expiry refusal
/// has its own unit test in `axiam-pki` where the `time` crate is available to
/// build an expired one.
fn external_ca(cn: &str) -> (String, String) {
    let key_pair = rcgen::KeyPair::generate_for(&rcgen::PKCS_ED25519).unwrap();
    let mut params = rcgen::CertificateParams::new(Vec::<String>::new()).unwrap();
    params
        .distinguished_name
        .push(rcgen::DnType::CommonName, cn);
    params.is_ca = rcgen::IsCa::Ca(rcgen::BasicConstraints::Unconstrained);
    let cert = params.self_signed(&key_pair).unwrap();
    (key_pair.serialize_pem(), cert.pem())
}

