#[actix_web::test]
async fn import_takes_custody_of_a_supplied_key() {
    let (db, org_id, tenant_id) = setup_db().await;
    let user_id = create_admin_user(&db, tenant_id).await;
    let auth = test_auth_config();
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let app = test_app!(db, auth);
    let (key_pem, cert_pem) = external_ca("Acme Offline Root");

    let (status, body) = post_import(
        &app,
        org_id,
        &token,
        serde_json::json!({
            "public_cert_pem": cert_pem,
            "private_key_pem": key_pem,
        }),
    )
    .await;

    assert_eq!(status, 201, "{body}");
    // Everything the record says comes from the certificate, not the request —
    // which never named a subject, a validity window or an algorithm.
    assert_eq!(body["subject"], "Acme Offline Root");
    assert_eq!(body["key_algorithm"], "Ed25519");
    assert_eq!(body["status"], "Active");
    assert_eq!(body["key_custody"], "database");
    // And the key itself never comes back out.
    assert!(body.get("private_key_pem").is_none(), "{body}");
    assert!(body.get("encrypted_private_key").is_none(), "{body}");
}

