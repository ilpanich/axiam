/// A token for an administrator living in the organization's own reserved
/// tenant — for the one step in these tests that needs one.
///
/// Minting a CA is an organization-level action (B-04): a CA is the
/// organization's, and whoever holds its private key can sign certificates that
/// authenticate as principals in any tenant under it. So
/// `require_organization_principal` refuses `POST
/// /organizations/{id}/ca-certificates` to a tenant principal, whatever
/// permissions it holds, and the CA these tests need as a fixture cannot be
/// minted with the tenant token.
///
/// The leaf certificates this file is actually about stay tenant-level and keep
/// using the tenant token, which is the point: only the fixture step changes
/// principal, not the behaviour under test.
async fn organization_ca_token(db: &Surreal<TestDb>, auth: &AuthConfig, org_id: Uuid) -> String {
    let org_tenant = SurrealTenantRepository::new(db.clone())
        .create(CreateTenant::organization_scope(org_id))
        .await
        .unwrap();
    let user = SurrealUserRepository::new(db.clone())
        .create(CreateUser {
            tenant_id: org_tenant.id,
            username: "org-admin".into(),
            email: "org-admin@example.com".into(),
            password: TEST_PASSWORD.into(),
            metadata: None,
        })
        .await
        .unwrap();
    mint_token(auth, user.id, org_tenant.id, org_id)
}

fn mint_token(auth: &AuthConfig, user_id: Uuid, tenant_id: Uuid, org_id: Uuid) -> String {
    issue_access_token(
        user_id,
        tenant_id,
        org_id,
        &[],
        auth,
        uuid::Uuid::new_v4().to_string(),
        axiam_auth::token::AUD_USER,
    )
    .unwrap()
}

macro_rules! test_app {
    ($db:expr, $auth:expr) => {{
        let pki_config = test_pki_config();
        let ca_repo = SurrealCaCertificateRepository::new($db.clone());
        let cert_repo = SurrealCertificateRepository::new($db.clone());
        test::init_service(
            App::new()
                .app_data(web::Data::new($auth.clone()))
                .app_data(web::Data::new({
                    let mut state = AppState::for_test($db.clone(), $auth.clone());
                    state.pki.ca_service = CaService::new(
                        ca_repo.clone(),
                        pki_config.clone(),
                        std::sync::Arc::new(tokio::sync::Semaphore::new(4)),
                        test_ca_custodians(),
                    );
                    state.pki.cert_service = CertService::new(
                        ca_repo,
                        cert_repo,
                        pki_config,
                        std::sync::Arc::new(tokio::sync::Semaphore::new(4)),
                        test_ca_custodians(),
                    );
                    state
                }))
                .app_data(web::Data::new(
                    Arc::new(AllowAllAuthzChecker) as Arc<dyn AuthzChecker>
                ))
                .configure(|cfg| {
                    register_api_v1_routes::<TestDb>(cfg, &RateLimitConfig::default())
                }),
        )
        .await
    }};
}

/// Helper macro: generate a CA certificate and return its ID.
macro_rules! generate_ca {
    ($app:expr, $org_id:expr, $token:expr) => {{
        let req = test::TestRequest::post()
            .uri(&format!(
                "/api/v1/organizations/{}/ca-certificates",
                $org_id
            ))
            .insert_header(("Authorization", format!("Bearer {}", $token)))
            .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
            .insert_header(("X-CSRF-Token", CSRF_TOKEN))
            .insert_header(("Content-Type", "application/json"))
            .set_json(serde_json::json!({
                "subject": "Test CA",
                "key_algorithm": "Ed25519",
                "validity_days": 365
            }))
            .to_request();
        let resp = test::call_service(&$app, req).await;
        assert_eq!(resp.status().as_u16(), 201);
        let body: serde_json::Value = test::read_body_json(resp).await;
        body["id"].as_str().unwrap().to_string()
    }};
}

/// The tenant signing CA a leaf is issued under.
///
/// Since S-1 a tenant principal reaches exactly one CA: the one that signs for
/// the tenant it is acting on. The organization CA above it is reachable only
/// by a principal living in the organization scope, so every leaf test here
/// needs the two-tier shape the product actually deploys — which is the shape
/// tenant signing CAs were added for in the first place.
///
/// 364 days rather than 365: an intermediate may not outlive the CA that signed
/// it, and the parent was minted for 365 days a moment ago.
macro_rules! tenant_signing_ca {
    ($app:expr, $org_id:expr, $tenant_id:expr, $ca_token:expr, $parent:expr) => {{
        let req = test::TestRequest::post()
            .uri(&format!(
                "/api/v1/organizations/{}/tenants/{}/signing-cas",
                $org_id, $tenant_id
            ))
            .insert_header(("Authorization", format!("Bearer {}", $ca_token)))
            .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
            .insert_header(("X-CSRF-Token", CSRF_TOKEN))
            .insert_header(("Content-Type", "application/json"))
            .set_json(serde_json::json!({
                "parent_ca_id": $parent,
                "subject": "Tenant Signing CA",
                "key_algorithm": "Ed25519",
                "validity_days": 364
            }))
            .to_request();
        let resp = test::call_service(&$app, req).await;
        let status = resp.status().as_u16();
        let body: serde_json::Value = test::read_body_json(resp).await;
        assert_eq!(status, 201, "tenant signing CA: {body}");
        body["id"].as_str().unwrap().to_string()
    }};
}

#[actix_rt::test]
async fn generate_certificate_signed_by_ca() {
    let (db, org_id, tenant_id) = setup_db().await;
    let auth = test_auth_config();
    let user_id = create_admin_user(&db, tenant_id).await;
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let ca_token = organization_ca_token(&db, &auth, org_id).await;
    let app = test_app!(db, auth);

    let org_ca_id = generate_ca!(app, org_id, ca_token);
    let ca_id = tenant_signing_ca!(app, org_id, tenant_id, ca_token, org_ca_id);

    let req = test::TestRequest::post()
        .uri("/api/v1/certificates")
        .insert_header(("Authorization", format!("Bearer {token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({
            "issuer_ca_id": ca_id,
            "subject": "device-001",
            "cert_type": "Device",
            "key_algorithm": "Ed25519",
            "validity_days": 90
        }))
        .to_request();

    let resp = test::call_service(&app, req).await;
    let status = resp.status().as_u16();
    let body: serde_json::Value = test::read_body_json(resp).await;
    assert_eq!(status, 201, "body: {body}");
    assert!(
        body["private_key_pem"]
            .as_str()
            .unwrap()
            .contains("PRIVATE KEY")
    );
    assert!(
        body["public_cert_pem"]
            .as_str()
            .unwrap()
            .contains("CERTIFICATE")
    );
    assert_eq!(body["cert_type"], "Device");
    assert_eq!(body["status"], "Active");
    assert_eq!(body["issuer_ca_id"], ca_id);
}

/// #649 — a subject that would write a line of its own into a log, a RADIUS
/// table or an ACL is a `400` on every way a name reaches a certificate, and
/// nothing is issued: no leaf, and no second CA beside the two the test made.
#[actix_rt::test]
async fn a_subject_with_a_control_character_is_a_400_and_issues_nothing() {
    let (db, org_id, tenant_id) = setup_db().await;
    let auth = test_auth_config();
    let user_id = create_admin_user(&db, tenant_id).await;
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let ca_token = organization_ca_token(&db, &auth, org_id).await;
    let app = test_app!(db, auth);

    let org_ca_id = generate_ca!(app, org_id, ca_token);
    let ca_id = tenant_signing_ca!(app, org_id, tenant_id, ca_token, org_ca_id);

    let long = "a".repeat(65);
    let bad_subjects = [
        "device\n001",
        "device-001\n",
        "dev\tice",
        "dev\u{0}ice",
        "CN=dev\r\nice",
        "press\u{202E}07",
        "press\u{200B}07",
        long.as_str(),
    ];

    for subject in bad_subjects {
        let req = test::TestRequest::post()
            .uri("/api/v1/certificates")
            .insert_header(("Authorization", format!("Bearer {token}")))
            .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
            .insert_header(("X-CSRF-Token", CSRF_TOKEN))
            .insert_header(("Content-Type", "application/json"))
            .set_json(serde_json::json!({
                "issuer_ca_id": ca_id,
                "subject": subject,
                "cert_type": "Device",
                "key_algorithm": "Ed25519",
                "validity_days": 90
            }))
            .to_request();
        let resp = test::call_service(&app, req).await;
        assert_eq!(resp.status().as_u16(), 400, "{subject:?} must be a 400");
        let body: serde_json::Value = test::read_body_json(resp).await;
        let message = body["message"].as_str().unwrap_or_default();
        assert!(
            !message.contains('\n') && !message.contains('\u{202E}'),
            "the refusal must not echo the subject back: {message:?}"
        );
    }

    // The same value through the other doors: a root CA, a tenant signing CA
    // and a caller's CSR.
    let req = test::TestRequest::post()
        .uri(&format!("/api/v1/organizations/{org_id}/ca-certificates"))
        .insert_header(("Authorization", format!("Bearer {ca_token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({
            "subject": "Root\nCA", "key_algorithm": "Ed25519", "validity_days": 365
        }))
        .to_request();
    assert_eq!(test::call_service(&app, req).await.status().as_u16(), 400);

    let req = test::TestRequest::post()
        .uri(&format!(
            "/api/v1/organizations/{org_id}/tenants/{tenant_id}/signing-cas"
        ))
        .insert_header(("Authorization", format!("Bearer {ca_token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({
            "parent_ca_id": org_ca_id, "subject": long,
            "key_algorithm": "Ed25519", "validity_days": 364
        }))
        .to_request();
    assert_eq!(test::call_service(&app, req).await.status().as_u16(), 400);

    for cn in ["dev\nice", long.as_str()] {
        let req = test::TestRequest::post()
            .uri("/api/v1/certificates/sign-csr")
            .insert_header(("Authorization", format!("Bearer {token}")))
            .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
            .insert_header(("X-CSRF-Token", CSRF_TOKEN))
            .insert_header(("Content-Type", "application/json"))
            .set_json(serde_json::json!({
                "issuer_ca_id": ca_id, "csr_pem": plain_csr(cn),
                "cert_type": "Device", "validity_days": 30
            }))
            .to_request();
        let resp = test::call_service(&app, req).await;
        assert_eq!(resp.status().as_u16(), 400, "a CSR named {cn:?}");
    }

    // Nothing was issued by any of them.
    let req = test::TestRequest::get()
        .uri("/api/v1/certificates")
        .insert_header(("Authorization", format!("Bearer {token}")))
        .to_request();
    let resp = test::call_service(&app, req).await;
    assert_eq!(resp.status().as_u16(), 200);
    let body: serde_json::Value = test::read_body_json(resp).await;
    assert_eq!(body["total"], 0, "no certificate may have been stored");

    // And the same request with a clean name is issued, so the 400s above are
    // the subject's and not the fixture's.
    let req = test::TestRequest::post()
        .uri("/api/v1/certificates")
        .insert_header(("Authorization", format!("Bearer {token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({
            "issuer_ca_id": ca_id, "subject": "a".repeat(64), "cert_type": "Device",
            "key_algorithm": "Ed25519", "validity_days": 90
        }))
        .to_request();
    assert_eq!(test::call_service(&app, req).await.status().as_u16(), 201);
}

