/// A leaf that would outlive its issuer is refused, and the error says by how
/// much it may live instead.
///
/// It used to be silently shortened to the CA's expiry: an operator asked for a
/// year against a 30-day CA, got 30 days, and nothing said so. A certificate
/// whose holder believes it is valid for longer than its chain validates is a
/// renewal that does not happen and an outage nobody predicted.
#[actix_rt::test]
async fn a_leaf_outliving_its_issuer_is_refused_with_the_real_maximum() {
    let (db, org_id, tenant_id) = setup_db().await;
    let auth = test_auth_config();
    let user_id = create_admin_user(&db, tenant_id).await;
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let app = test_app!(db, auth);

    // The CA is issued for 365 days a moment ago, so it has 364 WHOLE days left.
    let ca_id = generate_ca!(app, org_id, token);

    let req = test::TestRequest::post()
        .uri("/api/v1/certificates")
        .insert_header(("Authorization", format!("Bearer {token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({
            "issuer_ca_id": ca_id,
            "subject": "too-long",
            "cert_type": "Service",
            "key_algorithm": "Ed25519",
            // 365, not something larger. A bigger number never reaches the
            // issuer-expiry check at all: the tenant's own `max_validity_days`
            // cap (365 by default) refuses it first, with a message about the
            // tenant policy that says nothing about the CA. 365 is the smallest
            // request that clears every earlier gate and still outlives this
            // issuer — by the seconds that elapsed between the two calls.
            "validity_days": 365
        }))
        .to_request();

    let resp = test::call_service(&app, req).await;
    let status = resp.status().as_u16();
    let body: serde_json::Value = test::read_body_json(resp).await;
    assert_eq!(status, 400, "body: {body}");

    // The number is the point: an error that only says "too long" leaves the
    // operator guessing at the value the form should have offered. The CA was
    // issued moments ago for 365 days, so whole days remaining is 364.
    let message = body.to_string();
    assert!(
        message.contains("cannot outlive its issuer"),
        "the refusal must say why, got: {message}"
    );
    assert!(
        message.contains("364 days"),
        "the refusal must quote the maximum the issuer can grant, got: {message}"
    );
}

#[actix_rt::test]
async fn certificate_endpoints_require_auth() {
    let (db, _org_id, _tenant_id) = setup_db().await;
    let auth = test_auth_config();
    let app = test_app!(db, auth);

    let endpoints = vec![
        ("POST", "/api/v1/certificates".to_string()),
        ("GET", "/api/v1/certificates".to_string()),
        ("GET", format!("/api/v1/certificates/{}", Uuid::new_v4())),
        (
            "POST",
            format!("/api/v1/certificates/{}/revoke", Uuid::new_v4()),
        ),
    ];

    for (method, uri) in endpoints {
        let req = match method {
            "POST" => test::TestRequest::post()
                .uri(&uri)
                .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
                .insert_header(("X-CSRF-Token", CSRF_TOKEN))
                .to_request(),
            _ => test::TestRequest::get().uri(&uri).to_request(),
        };
        let resp = test::call_service(&app, req).await;
        assert_eq!(
            resp.status().as_u16(),
            401,
            "{method} {uri} should require auth"
        );
    }
}
