/// URL-encode a PEM string for the X-Client-Certificate header.
fn urlencode(input: &str) -> String {
    let mut result = String::with_capacity(input.len() * 3);
    for byte in input.bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                result.push(byte as char);
            }
            _ => {
                result.push('%');
                result.push_str(&format!("{:02X}", byte));
            }
        }
    }
    result
}

#[actix_rt::test]
async fn device_auth_full_flow() {
    let (db, org_id, tenant_id) = setup_db().await;
    let auth = test_auth_config();
    let user_id = create_admin_user(&db, tenant_id).await;
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let ca_token = organization_ca_token(&db, &auth, org_id).await;
    let app = test_app!(db, auth);

    // 1. Generate CA
    let ca_id = generate_ca!(app, org_id, ca_token);
    flag_trust_anchor(&db, org_id, &ca_id).await;

    // 2. Generate device certificate
    let (cert_id, public_cert_pem) = generate_device_cert!(app, ca_id, token);

    // 3. Create service account
    let sa_id = create_service_account!(app, token);

    // 4. Bind certificate to service account
    let req = test::TestRequest::post()
        .uri(&format!(
            "/api/v1/service-accounts/{sa_id}/bind-certificate"
        ))
        .insert_header(("Authorization", format!("Bearer {token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({
            "certificate_id": cert_id
        }))
        .to_request();
    let resp = test::call_service(&app, req).await;
    let status = resp.status().as_u16();
    let body: serde_json::Value = test::read_body_json(resp).await;
    assert_eq!(status, 200, "bind failed: {body}");

    // 5. Authenticate via device cert
    let encoded_pem = urlencode(&public_cert_pem);
    let req = test::TestRequest::post()
        .uri("/api/v1/auth/device")
        .insert_header(("X-Client-Certificate", encoded_pem.as_str()))
        .to_request();
    let resp = test::call_service(&app, req).await;
    let status = resp.status().as_u16();
    let body: serde_json::Value = test::read_body_json(resp).await;
    assert_eq!(status, 200, "device auth failed: {body}");
    assert!(body["access_token"].as_str().unwrap().len() > 10);
    assert_eq!(body["token_type"], "Bearer");
}

#[actix_rt::test]
async fn device_auth_mints_service_account_sub_kind() {
    // FUNC-04 (D-09): the SA cert-auth device-auth path mints a token whose
    // decoded sub_kind claim is ServiceAccount (not the default User).
    let (db, org_id, tenant_id) = setup_db().await;
    let auth = test_auth_config();
    let user_id = create_admin_user(&db, tenant_id).await;
    let token = mint_token(&auth, user_id, tenant_id, org_id);
    let ca_token = organization_ca_token(&db, &auth, org_id).await;
    let app = test_app!(db, auth.clone());

    let ca_id = generate_ca!(app, org_id, ca_token);
    flag_trust_anchor(&db, org_id, &ca_id).await;
    let (cert_id, public_cert_pem) = generate_device_cert!(app, ca_id, token);
    let sa_id = create_service_account!(app, token);

    let req = test::TestRequest::post()
        .uri(&format!(
            "/api/v1/service-accounts/{sa_id}/bind-certificate"
        ))
        .insert_header(("Authorization", format!("Bearer {token}")))
        .insert_header(("Cookie", format!("axiam_csrf={CSRF_TOKEN}")))
        .insert_header(("X-CSRF-Token", CSRF_TOKEN))
        .insert_header(("Content-Type", "application/json"))
        .set_json(serde_json::json!({ "certificate_id": cert_id }))
        .to_request();
    let resp = test::call_service(&app, req).await;
    assert_eq!(resp.status().as_u16(), 200);

    let encoded_pem = urlencode(&public_cert_pem);
    let req = test::TestRequest::post()
        .uri("/api/v1/auth/device")
        .insert_header(("X-Client-Certificate", encoded_pem.as_str()))
        .to_request();
    let resp = test::call_service(&app, req).await;
    assert_eq!(resp.status().as_u16(), 200);
    let body: serde_json::Value = test::read_body_json(resp).await;
    let access_token = body["access_token"].as_str().unwrap();

    let claims = decode_access_token(access_token, &auth).unwrap();
    assert_eq!(claims.sub_kind, SubjectKind::ServiceAccount);

    // §17.2 residual 1: the device path now mints the MACHINE audience. It
    // used to stamp `axiam:user`, which meant a certificate-authenticated
    // device passed every user-facing route guard — the same principal got a
    // user token by certificate and a machine token by secret, leaving the
    // SEC-006 / §4.3 narrowing half applied.
    //
    // Nothing pinned the audience on this path before, which is why the flip
    // was invisible to this suite.
    assert_eq!(
        claims.aud.as_deref(),
        Some(axiam_auth::token::AUD_M2M),
        "a device token must carry the machine audience"
    );

    // And the narrowing must actually bite: the same token is refused by a
    // user-facing route. Without this the assertion above only pins a string.
    let req = test::TestRequest::get()
        .uri("/api/v1/users")
        .insert_header(("Authorization", format!("Bearer {access_token}")))
        .to_request();
    let resp = test::call_service(&app, req).await;
    assert_eq!(
        resp.status().as_u16(),
        401,
        "a device token must not be accepted on a user-facing route"
    );
}

