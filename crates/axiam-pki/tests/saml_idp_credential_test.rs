/// The PKI encryption key, built once per process from random bytes so no key
/// literal is in the source and a CA generated by one service opens in another.
fn pki_encryption_key() -> [u8; 32] {
    static KEY: OnceLock<[u8; 32]> = OnceLock::new();
    *KEY.get_or_init(|| {
        let mut bytes = [0u8; 32];
        bytes[..16].copy_from_slice(Uuid::new_v4().as_bytes());
        bytes[16..].copy_from_slice(Uuid::new_v4().as_bytes());
        bytes
    })
}

fn custodians() -> Arc<axiam_pki::CaKeyCustodians> {
    Arc::new(
        axiam_pki::custodians_from_env(Some(pki_encryption_key())).expect("test CA custodians"),
    )
}

fn pki_config() -> PkiConfig {
    PkiConfig {
        encryption_key: Some(pki_encryption_key()),
        ..Default::default()
    }
}

type Creds = SurrealSamlIdpCredentialRepository<Db>;
type CredService = SamlIdpCredentialService<
    SurrealCaCertificateRepository<Db>,
    SurrealCertificateRepository<Db>,
    Creds,
>;

struct Rig {
    cas: CaService<SurrealCaCertificateRepository<Db>>,
    ca_repo: SurrealCaCertificateRepository<Db>,
    certs: CertService<SurrealCaCertificateRepository<Db>, SurrealCertificateRepository<Db>>,
    cert_repo: SurrealCertificateRepository<Db>,
    creds: Creds,
    svc: CredService,
}

async fn rig() -> Rig {
    let db = Surreal::new::<Mem>(()).await.unwrap();
    db.use_ns("test").use_db("test").await.unwrap();
    axiam_db::run_migrations(&db).await.unwrap();
    let ca_repo = SurrealCaCertificateRepository::new(db.clone());
    let cert_repo = SurrealCertificateRepository::new(db.clone());
    let creds = SurrealSamlIdpCredentialRepository::new(db.clone());
    let sem = Arc::new(tokio::sync::Semaphore::new(4));
    let certs = CertService::new(
        ca_repo.clone(),
        cert_repo.clone(),
        pki_config(),
        sem.clone(),
        custodians(),
    );
    Rig {
        cas: CaService::new(ca_repo.clone(), pki_config(), sem, custodians()),
        svc: SamlIdpCredentialService::new(certs.clone(), custodians(), creds.clone()),
        certs,
        ca_repo,
        cert_repo,
        creds,
    }
}

impl Rig {
    /// An organization root CA and, beneath it, a signing CA for `tenant_id`.
    /// Returns `(root, tenant signing CA)`.
    async fn tenant_ca(
        &self,
        org_id: Uuid,
        tenant_id: Uuid,
        validity_days: u32,
    ) -> (CaCertificate, CaCertificate) {
        let root = self
            .cas
            .generate(CreateCaCertificate {
                organization_id: org_id,
                subject: "Test Org Root CA".into(),
                key_algorithm: KeyAlgorithm::Ed25519,
                validity_days: 3650,
                intermediate_subject: None,
                intermediate_validity_days: None,
                issue_from_root: false,
            })
            .await
            .expect("root CA")
            .certificate;
        let signing = self
            .cas
            .generate_intermediate(CreateIntermediateCa {
                organization_id: org_id,
                tenant_id,
                parent_ca_id: root.id,
                subject: "Tenant Signing CA".into(),
                key_algorithm: KeyAlgorithm::Ed25519,
                validity_days,
            })
            .await
            .expect("tenant signing CA")
            .certificate;
        (root, signing)
    }
}

fn with_cert<T>(pem: &str, f: impl FnOnce(&X509Certificate<'_>) -> T) -> T {
    let (_, block) = x509_parser::pem::parse_x509_pem(pem.as_bytes()).expect("PEM");
    let (_, cert) = X509Certificate::from_der(&block.contents).expect("DER");
    f(&cert)
}

fn der_of(pem: &str) -> Vec<u8> {
    x509_parser::pem::parse_x509_pem(pem.as_bytes())
        .expect("PEM")
        .1
        .contents
}

fn contains_subslice(haystack: &[u8], needle: &[u8]) -> bool {
    !needle.is_empty() && haystack.windows(needle.len()).any(|w| w == needle)
}

