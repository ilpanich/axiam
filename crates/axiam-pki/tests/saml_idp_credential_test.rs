#[tokio::test]
async fn issuance_refuses_a_ca_it_may_not_use() {
    let rig = rig().await;
    let (org, tenant) = (Uuid::new_v4(), Uuid::new_v4());
    let (root, ca) = rig.tenant_ca(org, tenant, 365).await;
    let issue = |org: Uuid, tenant: Uuid, scope: IssuingScope, ca_id: Uuid, days: u32| {
        let svc = rig.svc.clone();
        async move {
            svc.issue(
                org,
                tenant,
                scope,
                ca_id,
                days,
                SamlIdpCredentialStatus::Active,
            )
            .await
        }
    };

    // Another organization's CA: not found, not usable.
    let other_org = Uuid::new_v4();
    let (_other_root, other_ca) = rig.tenant_ca(other_org, tenant, 365).await;
    assert!(matches!(
        issue(org, tenant, IssuingScope::Tenant, other_ca.id, 30).await,
        Err(AxiamError::NotFound { .. })
    ));
    // Another tenant's signing CA in the same organization.
    let other_tenant = Uuid::new_v4();
    let other_tenant_ca = rig
        .cas
        .generate_intermediate(CreateIntermediateCa {
            organization_id: org,
            tenant_id: other_tenant,
            parent_ca_id: root.id,
            subject: "Other Tenant CA".into(),
            key_algorithm: KeyAlgorithm::Ed25519,
            validity_days: 365,
        })
        .await
        .unwrap()
        .certificate;
    assert!(matches!(
        issue(org, tenant, IssuingScope::Tenant, other_tenant_ca.id, 30).await,
        Err(AxiamError::NotFound { .. })
    ));
    // The organization anchor, for a tenant-scope caller.
    assert!(matches!(
        issue(org, tenant, IssuingScope::Tenant, root.id, 30).await,
        Err(AxiamError::NotFound { .. })
    ));

    // A non-signing CA: an imported one whose key AXIAM never held.
    let csr = {
        let pair = rcgen::KeyPair::generate_for(&rcgen::PKCS_ED25519).unwrap();
        let mut params = rcgen::CertificateParams::new(Vec::<String>::new()).unwrap();
        params
            .distinguished_name
            .push(rcgen::DnType::CommonName, "Offline Tenant CA");
        params.serialize_request(&pair).unwrap().pem().unwrap()
    };
    let offline_tenant = Uuid::new_v4();
    let offline = rig
        .cas
        .sign_intermediate_csr(SignIntermediateCsr {
            organization_id: org,
            tenant_id: offline_tenant,
            parent_ca_id: root.id,
            csr_pem: csr,
            validity_days: 365,
        })
        .await
        .unwrap();
    assert_eq!(offline.key_custody, CaKeyCustody::External);
    let refused = issue(org, offline_tenant, IssuingScope::Tenant, offline.id, 30)
        .await
        .expect_err("a CA with no key cannot sign");
    assert!(
        refused.to_string().contains("private key"),
        "the refusal should say the CA holds no key"
    );

    // An expired CA (a row whose window has closed).
    let now = Utc::now();
    let expired_tenant = Uuid::new_v4();
    let expired = rig
        .ca_repo
        .create(StoreCaCertificate {
            id: Uuid::new_v4(),
            organization_id: org,
            tenant_id: Some(expired_tenant),
            parent_ca_id: Some(root.id),
            subject: "Expired Tenant CA".into(),
            public_cert_pem: ca.public_cert_pem.clone(),
            chain_pem: None,
            fingerprint: format!("expired-{}", Uuid::new_v4().simple()),
            key_algorithm: KeyAlgorithm::Ed25519,
            not_before: now - Duration::days(10),
            not_after: now - Duration::days(1),
            encrypted_private_key: ca.encrypted_private_key.clone(),
            key_custody: CaKeyCustody::Database,
            key_locator: None,
        })
        .await
        .unwrap();
    let refused = issue(org, expired_tenant, IssuingScope::Tenant, expired.id, 30)
        .await
        .expect_err("expired");
    assert!(refused.to_string().contains("expired"));

    // A revoked CA.
    rig.cas.revoke(org, ca.id).await.unwrap();
    assert!(
        issue(org, tenant, IssuingScope::Tenant, ca.id, 30)
            .await
            .is_err()
    );

    // Nothing was stored by any refusal.
    assert!(rig.creds.list(tenant).await.unwrap().is_empty());
}

#[tokio::test]
async fn issuance_refuses_a_validity_outside_one_to_730_days_and_a_retired_status() {
    let rig = rig().await;
    let (org, tenant) = (Uuid::new_v4(), Uuid::new_v4());
    let (_root, ca) = rig.tenant_ca(org, tenant, 1825).await;
    assert_eq!(MAX_SAML_IDP_CREDENTIAL_VALIDITY_DAYS, 730);

    for days in [0u32, 731, 825, 3650] {
        assert!(
            matches!(
                rig.svc
                    .issue(
                        org,
                        tenant,
                        IssuingScope::Tenant,
                        ca.id,
                        days,
                        SamlIdpCredentialStatus::Active
                    )
                    .await,
                Err(AxiamError::Validation { .. })
            ),
            "{days} days must be refused"
        );
    }
    assert!(matches!(
        rig.svc
            .issue(
                org,
                tenant,
                IssuingScope::Tenant,
                ca.id,
                30,
                SamlIdpCredentialStatus::Retired
            )
            .await,
        Err(AxiamError::Validation { .. })
    ));
    assert!(rig.creds.list(tenant).await.unwrap().is_empty());
}

