//! The SAML IdP signing credential — issuance, sealing, lookup, retirement
//! (T23.2.1, G-2, D-21).
//!
//! What these assert is not that a credential came back but that the right one
//! did: an RSA-4096 leaf with `digitalSignature` and `documentSigning` and
//! nothing else, chaining to the tenant's CA, whose private key is in the
//! datastore as ciphertext and decrypts back to the key that matches the
//! certificate. And that everything that must refuse it, does.
//!
//! No literal key or password appears here: the PKI encryption key is built from
//! random bytes at runtime, every certificate is generated, and no assertion
//! message formats a key, a certificate or a PEM.

