#[tokio::test]
async fn the_generic_issuance_paths_and_the_certificate_store_refuse_saml_signing() {
    let rig = rig().await;
    let (org, tenant) = (Uuid::new_v4(), Uuid::new_v4());
    let (_root, ca) = rig.tenant_ca(org, tenant, 365).await;

    let generated = rig
        .certs
        .generate(
            org,
            IssuingScope::Tenant,
            CreateCertificate {
                tenant_id: tenant,
                issuer_ca_id: ca.id,
                subject: "saml".into(),
                cert_type: CertificateType::SamlSigning,
                key_algorithm: KeyAlgorithm::Ed25519,
                validity_days: 30,
                metadata: None,
                subject_alt_names: vec![],
            },
            None,
            &[],
        )
        .await;
    assert!(matches!(generated, Err(AxiamError::Validation { .. })));

    let csr = {
        let pair = rcgen::KeyPair::generate_for(&rcgen::PKCS_ED25519).unwrap();
        let mut params = rcgen::CertificateParams::new(Vec::<String>::new()).unwrap();
        params
            .distinguished_name
            .push(rcgen::DnType::CommonName, "saml");
        params.serialize_request(&pair).unwrap().pem().unwrap()
    };
    let signed = rig
        .certs
        .sign_csr(
            org,
            IssuingScope::Tenant,
            SignCertificateCsr {
                tenant_id: tenant,
                issuer_ca_id: ca.id,
                csr_pem: csr,
                cert_type: CertificateType::SamlSigning,
                validity_days: 30,
                metadata: None,
                subject_alt_names: vec![],
            },
            None,
            &[],
        )
        .await;
    assert!(matches!(signed, Err(AxiamError::Validation { .. })));

    // And the store itself will not hold one: the schema's assertion refuses it.
    let now = Utc::now();
    let stored = rig
        .cert_repo
        .create(StoreCertificate {
            tenant_id: tenant,
            issuer_ca_id: ca.id,
            subject: "saml".into(),
            public_cert_pem: ca.public_cert_pem.clone(),
            fingerprint: Uuid::new_v4().simple().to_string(),
            cert_type: CertificateType::SamlSigning,
            key_algorithm: KeyAlgorithm::Ed25519,
            not_before: now,
            not_after: now + Duration::days(1),
            metadata: serde_json::json!({}),
        })
        .await;
    // Refused by the datastore's `cert_type` assertion (D-21: v72 does not widen it).
    assert!(stored.is_err(), "the certificate table must not hold one");
    assert!(
        rig.certs
            .list(
                tenant,
                axiam_core::repository::Pagination {
                    limit: 10,
                    ..Default::default()
                }
            )
            .await
            .unwrap()
            .items
            .is_empty()
    );
}
