/// Acceptance 1, 4 and 5 in one issuance (RSA-4096 generation is the expensive
/// step, so one credential carries every assertion about a good one).
#[tokio::test]
async fn an_issued_credential_has_the_saml_profile_chains_to_its_ca_and_seals_its_key() {
    let rig = rig().await;
    let (org, tenant) = (Uuid::new_v4(), Uuid::new_v4());
    let (_root, ca) = rig.tenant_ca(org, tenant, 1825).await;

    let credential = rig
        .svc
        .issue(
            org,
            tenant,
            IssuingScope::Tenant,
            ca.id,
            MAX_SAML_IDP_CREDENTIAL_VALIDITY_DAYS,
            SamlIdpCredentialStatus::Active,
        )
        .await
        .expect("issuance");

    assert_eq!(credential.tenant_id, tenant);
    assert_eq!(credential.issuer_ca_id, ca.id);
    assert_eq!(credential.status, SamlIdpCredentialStatus::Active);
    assert_eq!(credential.key_custody, CaKeyCustody::Database);

    // --- the certificate, parsed back ---
    with_cert(&credential.certificate_pem, |cert| {
        // digitalSignature only: no keyEncipherment even though the key is RSA.
        let ku = cert.key_usage().expect("readable").expect("present").value;
        assert!(ku.digital_signature());
        assert!(!ku.key_encipherment());
        assert_eq!(ku.flags, 1, "digitalSignature and nothing else");

        // documentSigning only — no serverAuth, no clientAuth.
        let eku = cert
            .extended_key_usage()
            .expect("readable")
            .expect("present")
            .value;
        assert!(!eku.any && !eku.server_auth && !eku.client_auth);
        assert!(!eku.code_signing && !eku.email_protection);
        assert!(!eku.time_stamping && !eku.ocsp_signing);
        let other: Vec<String> = eku.other.iter().map(|o| o.to_id_string()).collect();
        assert_eq!(other, vec!["1.3.6.1.5.5.7.3.36".to_string()]);

        // No SANs, and not a CA.
        assert!(cert.subject_alternative_name().expect("readable").is_none());
        assert!(
            cert.basic_constraints()
                .expect("readable")
                .is_none_or(|bc| !bc.value.ca)
        );

        // RSA-4096.
        match cert.public_key().parsed().expect("public key") {
            PublicKey::RSA(rsa) => assert_eq!(rsa.key_size(), 4096),
            _ => panic!("the SAML signing key must be RSA"),
        }

        // Chains to the tenant CA: issuer DN and a verifying signature.
        with_cert(&ca.public_cert_pem, |ca_cert| {
            assert_eq!(cert.issuer(), ca_cert.subject());
            cert.verify_signature(Some(ca_cert.public_key()))
                .expect("signed by the tenant signing CA");
        });

        // Validity: at most 730 days, never past the CA.
        let nb = cert.validity().not_before.timestamp();
        let na = cert.validity().not_after.timestamp();
        assert!(na - nb <= 730 * 86_400 + 60);
        assert!(na <= ca.not_after.timestamp());
        assert_eq!(na, credential.not_after.timestamp());

        // The row describes the certificate, not the request.
        assert_eq!(credential.serial, hex::encode(cert.raw_serial()));
    });
    assert_eq!(
        credential.fingerprint,
        hex::encode(Sha256::digest(der_of(&credential.certificate_pem)))
    );

    // --- it is not a `certificate` row, anywhere ---
    assert!(
        rig.certs
            .list(
                tenant,
                axiam_core::repository::Pagination {
                    limit: 100,
                    ..Default::default()
                }
            )
            .await
            .unwrap()
            .items
            .is_empty()
    );
    assert!(matches!(
        rig.certs
            .get_by_fingerprint(tenant, &credential.fingerprint)
            .await,
        Err(AxiamError::NotFound { .. })
    ));
    assert!(matches!(
        rig.cert_repo
            .get_by_fingerprint_global(&credential.fingerprint)
            .await,
        Err(AxiamError::NotFound { .. })
    ));

    // --- it authenticates nobody: device login / mTLS cannot find it ---
    let device_auth = DeviceAuthService::new(rig.cert_repo.clone(), rig.ca_repo.clone());
    assert!(
        device_auth
            .authenticate(&credential.certificate_pem)
            .await
            .is_err()
    );

    // --- the key at rest is ciphertext ---
    let stored = rig
        .creds
        .get_active_sealed(tenant)
        .await
        .unwrap()
        .expect("an active credential")
        .key
        .ciphertext
        .expect("sealed key");

    // --- ...and decrypts back to the key that goes with the certificate ---
    let opened = rig
        .svc
        .get_active_signing_key(org, tenant)
        .await
        .unwrap()
        .expect("an active credential");
    assert_eq!(opened.credential, credential);
    let pem_text: &str = &opened.private_key_pem;
    assert!(pem_text.contains("PRIVATE KEY"));
    assert!(
        !contains_subslice(&stored, pem_text.as_bytes()),
        "the stored bytes must not contain the PEM"
    );
    assert!(
        !contains_subslice(&stored, b"PRIVATE KEY"),
        "the stored bytes must not contain a PEM header"
    );
    let pair = rcgen::KeyPair::from_pem(pem_text).expect("the decrypted key is usable");
    with_cert(&credential.certificate_pem, |cert| {
        assert_eq!(
            rcgen::PublicKeyData::subject_public_key_info(&pair),
            cert.public_key().raw
        );
    });

    // Debug redacts the key.
    let shown = format!("{opened:?}");
    assert!(shown.contains("[REDACTED]"));
    assert!(!shown.contains("PRIVATE KEY"));

    // --- the slot is taken, refused before any key is generated ---
    assert!(matches!(
        rig.svc
            .issue(
                org,
                tenant,
                IssuingScope::Tenant,
                ca.id,
                30,
                SamlIdpCredentialStatus::Active
            )
            .await,
        Err(AxiamError::AlreadyExists { .. })
    ));

    // --- list and get_active return no key material, only facts ---
    assert_eq!(
        rig.svc.list(tenant).await.unwrap(),
        vec![credential.clone()]
    );
    assert_eq!(
        rig.svc.get_active(tenant).await.unwrap(),
        Some(credential.clone())
    );

    // --- another tenant sees and retires nothing ---
    let stranger = Uuid::new_v4();
    assert!(rig.svc.list(stranger).await.unwrap().is_empty());
    assert!(
        rig.svc
            .get_active_signing_key(org, stranger)
            .await
            .unwrap()
            .is_none()
    );
    assert!(matches!(
        rig.svc.retire(stranger, credential.id).await,
        Err(AxiamError::NotFound { .. })
    ));

    // --- retire destroys the key ---
    let retired = rig.svc.retire(tenant, credential.id).await.unwrap();
    assert_eq!(retired.status, SamlIdpCredentialStatus::Retired);
    assert!(
        rig.svc
            .get_active_signing_key(org, tenant)
            .await
            .unwrap()
            .is_none()
    );
    let sealed_left = rig.creds.get_active_sealed(tenant).await.unwrap().is_some();
    assert!(!sealed_left);
}

/// A credential can be issued into the `next` slot beside an active one, and the
/// signer's lookup finds only the active one.
#[tokio::test]
async fn a_next_credential_is_issued_beside_the_active_one() {
    let rig = rig().await;
    let (org, tenant) = (Uuid::new_v4(), Uuid::new_v4());
    let (_root, ca) = rig.tenant_ca(org, tenant, 365).await;

    let active = rig
        .svc
        .issue(
            org,
            tenant,
            IssuingScope::Tenant,
            ca.id,
            90,
            SamlIdpCredentialStatus::Active,
        )
        .await
        .unwrap();
    let next = rig
        .svc
        .issue(
            org,
            tenant,
            IssuingScope::Tenant,
            ca.id,
            90,
            SamlIdpCredentialStatus::Next,
        )
        .await
        .unwrap();

    assert_ne!(active.fingerprint, next.fingerprint);
    assert_eq!(rig.svc.list(tenant).await.unwrap().len(), 2);
    assert_eq!(
        rig.svc.get_active(tenant).await.unwrap().unwrap().id,
        active.id
    );
    assert_eq!(
        rig.svc
            .get_active_signing_key(org, tenant)
            .await
            .unwrap()
            .unwrap()
            .credential
            .id,
        active.id
    );
    // A third in either slot is refused.
    for status in [
        SamlIdpCredentialStatus::Active,
        SamlIdpCredentialStatus::Next,
    ] {
        assert!(matches!(
            rig.svc
                .issue(org, tenant, IssuingScope::Tenant, ca.id, 90, status)
                .await,
            Err(AxiamError::AlreadyExists { .. })
        ));
    }
}

/// The validity is bounded by the CA: a credential asking for what the CA has
/// left is granted and never outlives it.
#[tokio::test]
async fn the_validity_is_bounded_by_the_issuing_ca() {
    let rig = rig().await;
    let (org, tenant) = (Uuid::new_v4(), Uuid::new_v4());
    let (_root, ca) = rig.tenant_ca(org, tenant, 100).await;

    // One day more than the CA has left is refused, naming the number.
    let too_long = rig
        .svc
        .issue(
            org,
            tenant,
            IssuingScope::Tenant,
            ca.id,
            101,
            SamlIdpCredentialStatus::Active,
        )
        .await
        .expect_err("outlives its issuer");
    assert!(matches!(too_long, AxiamError::Validation { .. }));

    let granted = rig
        .svc
        .issue(
            org,
            tenant,
            IssuingScope::Tenant,
            ca.id,
            99,
            SamlIdpCredentialStatus::Active,
        )
        .await
        .expect("what the CA can grant");
    assert!(granted.not_after <= ca.not_after);
}

